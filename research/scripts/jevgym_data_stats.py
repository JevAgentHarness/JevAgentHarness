#!/usr/bin/env python3
"""JevGym task statistics from task generation only: every task of a frozen task list is rebuilt by the generator
(`bench/suites/jevgym.py`), its id is checked against the list, and its canonical (gold) plan is read. No episode runs,
no model is called, nothing is shown to a model (the same operation as `scripts/freeze_eval_tasks.py`).

    python scripts/jevgym_data_stats.py              # the Stage-2 list configs/eval/jevgym_stage2_tasks.json
    # -> results/data_stats/jevgym_eval.json and paper/generated/data_stats.tex (\\defres{data_stats/jevgym_eval/...})

Definitions: ``plan_steps`` = calls in the task's canonical plan including the final ``finish`` (the oracle route of
``JevGymEnv._plan``; the shortest successful episode has this many steps); ``plan_calls`` = the same without
``finish`` (the env's ``optimal_calls``); a *distinct plan* is a distinct sequence of tool names (the plan's shape;
arguments differ across every task); ``tools_offered`` = the tools System-2 and System-1 choose among (the suite's
tools, its distractors and ``finish``). The key prefix stays ``data_stats/jevgym_eval`` whatever list is read; the
population is recorded in the JSON and as ``data_stats/jevgym_eval/population``."""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Mapping

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

TASKS = ROOT / "configs/eval/jevgym_stage2_tasks.json"
OUT_JSON = ROOT / "results/data_stats/jevgym_eval.json"
OUT_TEX = ROOT / "paper/generated/data_stats.tex"
PREFIX = "data_stats/jevgym_eval"


def compute(frozen: Mapping[str, Any]) -> dict[str, Any]:
    from jevharness.bench.suites import load_suite

    suite = dict(frozen["suite"])
    facs = load_suite(suite.pop("name"), **suite)
    envs = [f() for f in facs]
    ids = [e.task_id for e in envs]
    if ids != list(frozen["task_ids"]):
        raise SystemExit("the generator no longer reproduces the frozen task list (ids differ): not computed")
    plans = [e._plan() for e in envs]
    steps = np.array([len(p) for p in plans], float)
    calls = np.array([len([t for t, _ in p if t != "finish"]) for p in plans], float)
    shapes = Counter(tuple(t for t, _ in p) for p in plans)
    offered = []
    for e in envs:
        e.reset()
        offered.append(len(list(e.tools())) + 1)      # + finish (harness/tools.py::finish_tool)
    fam = Counter(e.family for e in envs)
    by_fam = {f: {"n": n, "plan_steps_median": float(np.median([len(p) for p, e in zip(plans, envs) if e.family == f]))}
              for f, n in sorted(fam.items())}
    lo, hi = frozen.get("seed_range") or [None, None]
    return {"population": f"{frozen.get('registered', '')}: {Path(frozen.get('config', '')).name} seeds {lo}-{hi}",
            "tasks_file_sha256": frozen.get("sha256"), "n_tasks": len(envs), "n_families": len(fam),
            "plan_steps_median": float(np.median(steps)), "plan_steps_mean": float(steps.mean()),
            "plan_steps_min": float(steps.min()), "plan_steps_max": float(steps.max()),
            "plan_steps_p90": float(np.percentile(steps, 90)),
            "plan_calls_median": float(np.median(calls)), "plan_calls_mean": float(calls.mean()),
            "n_distinct_plans": len(shapes), "largest_plan_share": max(shapes.values()) / len(plans),
            "n_plan_tools": len({t for p in plans for t, _ in p}),
            "tools_offered_median": float(np.median(offered)), "by_family": by_fam,
            "distinct_plans": {" > ".join(k): v for k, v in shapes.most_common()}}


FMT = {"n_tasks": "{:.0f}", "n_families": "{:.0f}", "n_distinct_plans": "{:.0f}", "n_plan_tools": "{:.0f}",
       "plan_steps_min": "{:.0f}", "plan_steps_max": "{:.0f}", "tools_offered_median": "{:.0f}",
       "largest_plan_share": "{:.1f}"}


def to_tex(stats: Mapping[str, Any], generated: str) -> str:
    from jevharness.bench.paper_numbers import _seg, _tex_text

    vals: dict[str, str] = {f"{PREFIX}/population": _tex_text(str(stats["population"]))}
    for k, v in stats.items():
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            x = 100 * v if k == "largest_plan_share" else v
            vals[f"{PREFIX}/{k}"] = FMT.get(k, "{:.1f}").format(x)
    for f, r in stats["by_family"].items():
        vals[f"{PREFIX}/by_family/{_seg(f)}/n"] = f"{r['n']:.0f}"
        vals[f"{PREFIX}/by_family/{_seg(f)}/plan_steps_median"] = f"{r['plan_steps_median']:.1f}"
    lines = ["% AUTO-GENERATED by scripts/jevgym_data_stats.py (task generation only; no episode) -- do not edit.",
             f"% generated {generated}; population: {stats['population']}", r"\makeatletter",
             r"\providecommand{\res}[1]{\ifcsname jevres@#1\endcsname\csname jevres@#1\endcsname\else\tbd\fi}",
             r"\providecommand{\defres}[2]{\expandafter\def\csname jevres@#1\endcsname{#2}}"]
    lines += [f"\\defres{{{k}}}{{{v}}}" for k, v in sorted(vals.items())] + [r"\makeatother", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tasks", default=str(TASKS))
    ap.add_argument("--out", default=str(OUT_JSON))
    ap.add_argument("--tex", default=str(OUT_TEX))
    a = ap.parse_args(argv)
    path = Path(a.tasks)
    frozen = json.loads(path.read_text())
    stats = compute(frozen)
    generated = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    rec = {"generated": generated, "tasks_file": str(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path),
           "tasks_file_bytes_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
           "method": "task generation only (bench/suites/jevgym.py); no episode, no model", **stats}
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(rec, indent=1) + "\n")
    Path(a.tex).parent.mkdir(parents=True, exist_ok=True)
    Path(a.tex).write_text(to_tex(stats, generated))
    print(f"[data_stats] {stats['n_tasks']} tasks, plan steps median {stats['plan_steps_median']:.1f}, "
          f"{stats['n_distinct_plans']} distinct plans -> {a.out}, {a.tex}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
