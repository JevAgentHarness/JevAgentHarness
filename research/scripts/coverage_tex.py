#!/usr/bin/env python3
r"""Shared writer of ``paper/generated/coverage.tex`` (``\res{cov/...}``) for the two coverage analyses of decision-model
roles -- DESCRIPTIVE / POST HOC, offline (no model is called):

* ``scripts/coverage_ask_act.py`` -> ``results/explore/coverage/ask_act.{json,md}`` (``cov/ask/...``);
* ``scripts/coverage_gates.py``   -> ``results/explore/coverage/gates.{json,md}``   (``cov/gate/...``).

Each analysis writes its JSON with a ``tex`` map (key -> formatted TeX value); :func:`write_tex` merges the ``tex`` maps
of every analysis JSON present in the output directory, so either script can be re-run alone without dropping the other
one's keys.

    python scripts/coverage_tex.py          # rebuild coverage.tex from the committed JSONs only
"""
from __future__ import annotations

import datetime as dt
import json
import math
import subprocess
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "results/explore/coverage"
TEX_OUT = ROOT / "paper/generated/coverage.tex"
SOURCES = ("ask_act.json", "gates.json")          # the analyses whose ``tex`` maps make up coverage.tex
LABEL = "descriptive, post hoc (coverage of decision-model roles); offline, no model call; not a registered analysis"


def git_head() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except Exception:  # noqa: BLE001 - provenance only
        return "unknown"


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def rel(p: Path | str) -> str:
    p = Path(p)
    try:
        return str(p.resolve().relative_to(ROOT))
    except ValueError:
        return str(p)


def finite(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(float(x))


def pct(x: Any) -> str | None:
    """A share in [0, 1] as a percentage with one decimal (the paper's convention for rates)."""
    return f"{100.0 * float(x):.1f}" if finite(x) else None


def count(x: Any) -> str | None:
    """An integer count; thousands separated as in the other generated files (``3{,}754``)."""
    return f"{int(x):,}".replace(",", "{,}") if finite(x) else None


def two(x: Any) -> str | None:
    return f"{float(x):.2f}" if finite(x) else None


def put(tex: dict[str, str], key: str, value: str | None) -> None:
    """Store ``value`` under ``key`` unless it is missing (``\\res`` then prints the placeholder)."""
    if value is not None:
        tex[key] = value


def to_tex(maps: Sequence[tuple[str, Mapping[str, Any]]]) -> str:
    """The merged TeX file. ``maps`` = (source name, analysis JSON) pairs; a key defined twice is an error."""
    merged: dict[str, str] = {}
    for name, res in maps:
        for k, v in (res.get("tex") or {}).items():
            if k in merged and merged[k] != v:
                raise ValueError(f"coverage key {k} defined twice ({name})")
            merged[k] = str(v)
    head = ", ".join(f"{name} (git {str((res.get('meta') or {}).get('git', ''))[:12]}, "
                     f"{(res.get('meta') or {}).get('generated', '?')})" for name, res in maps)
    lines = ["% AUTO-GENERATED by scripts/coverage_ask_act.py and scripts/coverage_gates.py (via scripts/coverage_tex.py)"
             " -- do not edit by hand.",
             f"% {LABEL}; sources: {head or 'none'}",
             r"\makeatletter",
             r"\providecommand{\res}[1]{\ifcsname jevres@#1\endcsname\csname jevres@#1\endcsname\else\tbd\fi}",
             r"\providecommand{\defres}[2]{\expandafter\def\csname jevres@#1\endcsname{#2}}"]
    lines += [f"\\defres{{{k}}}{{{merged[k]}}}" for k in sorted(merged)]
    lines += [r"\makeatother", ""]
    return "\n".join(lines)


def write_tex(out_dir: Path = OUT_DIR, tex_out: Path = TEX_OUT) -> Path:
    maps = []
    for name in SOURCES:
        p = Path(out_dir) / name
        if p.exists():
            maps.append((name, json.loads(p.read_text())))
    tex_out = Path(tex_out)
    tex_out.parent.mkdir(parents=True, exist_ok=True)
    tex_out.write_text(to_tex(maps))
    return tex_out


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    ap.add_argument("--tex", default=str(TEX_OUT))
    a = ap.parse_args(argv)
    print(f"wrote {rel(write_tex(Path(a.out_dir), Path(a.tex)))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
